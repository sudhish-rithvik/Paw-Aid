/// AI Analysis Status
enum AIAnalysisStatus {
  pending('PENDING', 'Analyzing animal distress...'),
  completed('COMPLETED', 'Triage analysis completed'),
  unavailable('UNAVAILABLE', 'Local inference model not bundled on device'),
  error('ERROR', 'Analysis failed');

  final String code;
  final String message;
  const AIAnalysisStatus(this.code, this.message);

  static AIAnalysisStatus fromString(String? val) {
    if (val == null) return AIAnalysisStatus.unavailable;
    return AIAnalysisStatus.values.firstWhere(
      (e) => e.name.toLowerCase() == val.toLowerCase() || e.code.toUpperCase() == val.toUpperCase(),
      orElse: () => AIAnalysisStatus.unavailable,
    );
  }
}

/// Animal Triage Result
/// Encapsulates on-device vision triage output for emergency animal rescue.
///
/// IMPORTANT DISCLAIMER:
/// AI-generated severity is strictly preliminary emergency triage for dispatch prioritization.
/// It does NOT constitute a veterinary diagnosis or replace professional veterinary examination.
class AnimalTriageResult {
  final String reportId;
  final String modelId;
  final String animal;
  final double confidence;
  final List<String> visibleInjuries;
  final String mobility;
  final String painLevel;
  final String severity; // 'low', 'medium', 'high', 'critical'
  final int urgencyScore; // 1 to 10
  final String recommendedAction;
  final String reason;
  final AIAnalysisStatus status;
  final String triageDisclaimer;
  final DateTime analyzedAt;

  static const String defaultDisclaimer =
      'PRELIMINARY EMERGENCY TRIAGE ONLY: This assessment was generated by an on-device automated vision model to assist volunteer dispatch priority. It is NOT a professional veterinary diagnosis.';

  const AnimalTriageResult({
    required this.reportId,
    this.modelId = 'litert.animal-triage-contract-v1',
    required this.animal,
    required this.confidence,
    required this.visibleInjuries,
    required this.mobility,
    required this.painLevel,
    required this.severity,
    this.urgencyScore = 7,
    required this.recommendedAction,
    required this.reason,
    this.status = AIAnalysisStatus.completed,
    this.triageDisclaimer = defaultDisclaimer,
    required this.analyzedAt,
  });

  /// Factory for when no on-device model weights are bundled
  factory AnimalTriageResult.unavailable(String reportId) {
    return AnimalTriageResult(
      reportId: reportId,
      modelId: 'none',
      animal: 'Unknown',
      confidence: 0.0,
      visibleInjuries: const [],
      mobility: 'Unknown',
      painLevel: 'Unknown',
      severity: 'medium',
      urgencyScore: 5,
      recommendedAction: 'Awaiting human responder assessment.',
      reason: 'Local LiteRT model weights (.tflite) are not bundled in this build.',
      status: AIAnalysisStatus.unavailable,
      analyzedAt: DateTime.now(),
    );
  }

  /// Factory for in-progress analysis
  factory AnimalTriageResult.pending(String reportId) {
    return AnimalTriageResult(
      reportId: reportId,
      modelId: 'litert.triage',
      animal: 'Detecting...',
      confidence: 0.0,
      visibleInjuries: const [],
      mobility: 'Pending',
      painLevel: 'Pending',
      severity: 'medium',
      urgencyScore: 5,
      recommendedAction: 'Processing on-device camera frames...',
      reason: 'Inference running locally on device.',
      status: AIAnalysisStatus.pending,
      analyzedAt: DateTime.now(),
    );
  }

  Map<String, dynamic> toMap() => {
        'reportId': reportId,
        'modelId': modelId,
        'animal': animal,
        'animalDetected': animal,
        'confidence': confidence,
        'visible_injuries': visibleInjuries,
        'visibleInjuries': visibleInjuries,
        'injuriesDetected': visibleInjuries,
        'mobility': mobility,
        'mobilityAssessment': mobility,
        'pain_level': painLevel,
        'painLevel': painLevel,
        'severity': severity.toLowerCase(),
        'severityScore': severity.toUpperCase(),
        'urgencyScore': urgencyScore,
        'recommended_action': recommendedAction,
        'recommendedAction': recommendedAction,
        'reason': reason,
        'status': status.code,
        'aiAnalysisStatus': status.code,
        'triageDisclaimer': triageDisclaimer,
        'analyzedAt': analyzedAt.toUtc().toIso8601String(),
      };

  factory AnimalTriageResult.fromMap(Map<String, dynamic> map, [String? fallbackReportId]) {
    final repId = map['reportId'] as String? ?? fallbackReportId ?? '';
    final injuriesRaw = map['visible_injuries'] ?? map['visibleInjuries'] ?? map['injuriesDetected'];
    final List<String> injuries = injuriesRaw is List
        ? injuriesRaw.map((e) => e.toString()).toList()
        : (injuriesRaw is String && injuriesRaw.isNotEmpty ? [injuriesRaw] : []);

    return AnimalTriageResult(
      reportId: repId,
      modelId: map['modelId'] as String? ?? 'litert.animal-triage-contract-v1',
      animal: map['animal'] as String? ?? map['animalDetected'] as String? ?? 'Unknown',
      confidence: (map['confidence'] as num?)?.toDouble() ?? 0.0,
      visibleInjuries: injuries,
      mobility: map['mobility'] as String? ?? map['mobilityAssessment'] as String? ?? 'Unknown',
      painLevel: map['pain_level'] as String? ?? map['painLevel'] as String? ?? 'Unknown',
      severity: (map['severity'] as String? ?? map['severityScore'] as String? ?? 'medium').toLowerCase(),
      urgencyScore: (map['urgencyScore'] as num?)?.toInt() ?? 5,
      recommendedAction: map['recommended_action'] as String? ?? map['recommendedAction'] as String? ?? '',
      reason: map['reason'] as String? ?? '',
      status: AIAnalysisStatus.fromString(map['status'] as String? ?? map['aiAnalysisStatus'] as String?),
      triageDisclaimer: map['triageDisclaimer'] as String? ?? defaultDisclaimer,
      analyzedAt: map['analyzedAt'] != null
          ? DateTime.tryParse(map['analyzedAt'].toString()) ?? DateTime.now()
          : DateTime.now(),
    );
  }
}
